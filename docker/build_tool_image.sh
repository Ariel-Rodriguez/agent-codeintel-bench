#!/usr/bin/env bash
# Build a per-tool image that bakes dependencies and model caches, and write
# work/tool.env describing how to run it offline.
#
# Usage: docker/build_tool_image.sh <tool-dir> [image-tag]
#
# A tool may ship two optional hooks:
#   provision.sh  run at build time after dependency install (setup steps)
#   warmup.sh     run at build time to download model caches into /opt/tool-cache
set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(cd .. && pwd)"

TOOL_DIR="${1:?usage: build_tool_image.sh <tool-dir> [image-tag]}"
[ -d "$TOOL_DIR" ] || { echo "not a directory: $TOOL_DIR" >&2; exit 2; }
TOOL_DIR="$(cd "$TOOL_DIR" && pwd)"
NAME="${2:-$(basename "$TOOL_DIR")}"
BASE_IMAGE="${BASE_IMAGE:-agent-codeintel-bench}"
IMAGE="${TOOL_IMAGE:-agent-codeintel-bench-tool:$NAME}"

# Stage the tool into a build context.
CTX="$(mktemp -d)"
trap 'rm -rf "$CTX"' EXIT
mkdir -p "$CTX/tool/$NAME"
cp -R "$TOOL_DIR/." "$CTX/tool/$NAME/"

echo "building $IMAGE from $BASE_IMAGE (tool=$NAME)"
docker build \
  -f Dockerfile.tool \
  -t "$IMAGE" \
  --build-arg BASE_IMAGE="$BASE_IMAGE" \
  --build-arg TOOL_NAME="$NAME" \
  "$CTX"

# Detect the extension entry point declared by the tool.
ENTRY_REL="$(python3 - "$TOOL_DIR" <<'PY'
import json, os, sys
root = sys.argv[1]
entry = ""
pkg = os.path.join(root, "package.json")
if os.path.exists(pkg):
    try:
        data = json.load(open(pkg))
        exts = (data.get("pi") or {}).get("extensions") or []
        if exts:
            entry = exts[0].lstrip("./")
    except Exception:
        pass
if not entry:
    for cand in ("src/pi/index.ts", "src/index.ts", "index.ts", "index.js", "src/index.js", "dist/extension.js", "dist/index.js"):
        if os.path.exists(os.path.join(root, cand)):
            entry = cand
            break
print(entry)
PY
)"
TOOL_ENTRY="/opt/tools/$NAME/$ENTRY_REL"

mkdir -p "$ROOT/work"
cat > "$ROOT/work/tool.env" <<ENV
# Generated by docker/build_tool_image.sh — source before running.
export BENCH_IMAGE='$IMAGE'
export TOOL_IMAGE='$IMAGE'
export TOOL_PATH='/opt/tools/$NAME'
export TOOL_ENTRY='$TOOL_ENTRY'
ENV

echo "built: $IMAGE"
echo "entry: $TOOL_ENTRY"
echo
echo "next:"
echo "  source work/tool.env"
echo "  export ENHANCED_TOOLS='read,bash,edit,write,<tool-prefix>_*'   # if the tool adds tools"
echo "  UPSTREAM_BASE_URL=<model /v1> BENCH_IMAGE=\"\$BENCH_IMAGE\" docker/run.sh probe"
echo "  UPSTREAM_BASE_URL=<model /v1> BENCH_IMAGE=\"\$BENCH_IMAGE\" docker/run.sh run"
