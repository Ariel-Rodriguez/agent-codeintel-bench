#!/usr/bin/env bash
# Prepare baseline vs experiment from a repo and a tool to test.
#
# Usage:
#   harness/setup_test.sh [--repo <zip|dir>] [--tool <path>]
#                         [--tool-tools 'read,bash,edit,write,prefix_*']
#                         [--no-venv]
#
# Writes work/experiment-baseline, work/experiment-enhanced, isolated configs,
# and work/experiment.env (source it before running the suite).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REPO="$ROOT/fixtures/widget-service"
TOOL=""
TOOL_TOOLS="read,bash,edit,write"
BASE_TOOLS="read,bash,edit,write"
VENV=1
MODEL="${EXP_MODEL:-deepseek/deepseek-flash}"
THINKING="${EXP_THINKING:-high}"
SRC_AGENT="${PI_USER_AGENT_DIR:-$HOME/.pi/agent}"

while [ $# -gt 0 ]; do
  case "$1" in
    --repo) REPO="$2"; shift 2 ;;
    --tool) TOOL="$2"; shift 2 ;;
    --tool-tools) TOOL_TOOLS="$2"; shift 2 ;;
    --base-tools) BASE_TOOLS="$2"; shift 2 ;;
    --no-venv) VENV=0; shift ;;
    -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

command -v pi >/dev/null || { echo "unavailable: pi not found on PATH" >&2; exit 2; }

# Resolve the repo, unzipping if needed.
if [ -f "$REPO" ] && printf '%s' "$REPO" | grep -qi '\.zip$'; then
  mkdir -p "$ROOT/work/_repo_src"
  rm -rf "${ROOT:?}/work/_repo_src"/*
  unzip -q "$REPO" -d "$ROOT/work/_repo_src"
  # If the zip contains a single top-level directory, use it.
  entries=$(find "$ROOT/work/_repo_src" -mindepth 1 -maxdepth 1 | wc -l | tr -d ' ')
  if [ "$entries" = "1" ] && [ -d "$(find "$ROOT/work/_repo_src" -mindepth 1 -maxdepth 1)" ]; then
    REPO="$(find "$ROOT/work/_repo_src" -mindepth 1 -maxdepth 1)"
  else
    REPO="$ROOT/work/_repo_src"
  fi
fi
[ -d "$REPO" ] || { echo "unavailable: repo $REPO is not a directory or zip" >&2; exit 2; }

# Detect the extension entry point from the tool path.
CODEINTEL_EXT=""
if [ -n "$TOOL" ]; then
  if [ -f "$TOOL" ]; then
    CODEINTEL_EXT="$TOOL"
  elif [ -d "$TOOL" ]; then
    for cand in src/pi/index.ts index.ts src/index.ts dist/extension.js dist/index.js; do
      if [ -f "$TOOL/$cand" ]; then CODEINTEL_EXT="$TOOL/$cand"; break; fi
    done
  fi
fi

mkdir -p "$ROOT/work"
for arm in baseline enhanced; do
  wt="$ROOT/work/experiment-$arm"
  rm -rf "$wt"
  cp -R "$REPO" "$wt"
  ( cd "$wt" \
      && git init -q \
      && git add -A \
      && git -c user.email=bench@local -c user.name=bench commit -qm "fixture snapshot" )

  cfg="$ROOT/configs/$arm/pi-agent"
  sess="$ROOT/configs/$arm/sessions"
  mkdir -p "$cfg" "$sess"
  chmod 700 "$ROOT/configs/$arm" "$cfg" 2>/dev/null || true
  for f in auth.json models.json models-store.json; do
    [ -f "$SRC_AGENT/$f" ] && install -m 600 "$SRC_AGENT/$f" "$cfg/$f"
  done
  cat > "$cfg/settings.json" <<JSON
{
  "defaultProvider": "${MODEL%%/*}",
  "defaultModel": "${MODEL##*/}",
  "defaultThinkingLevel": "$THINKING",
  "packages": [],
  "enabledModels": ["$MODEL"]
}
JSON
  chmod 600 "$cfg/settings.json"

  # Optionally force all model traffic through the allowlisted gateway.
  if [ -n "${MODEL_GATEWAY:-}" ] && [ -f "$cfg/models.json" ]; then
    python3 - "$cfg/models.json" "${MODEL%%/*}" "$MODEL_GATEWAY" <<'PY'
import json, sys
path, provider, gateway = sys.argv[1], sys.argv[2], sys.argv[3]
data = json.load(open(path))
if provider in data.get("providers", {}):
    data["providers"][provider]["baseUrl"] = gateway
json.dump(data, open(path, "w"), indent=2)
PY
  fi

  if [ "$VENV" = "1" ] && { [ -f "$wt/pyproject.toml" ] || [ -f "$wt/setup.py" ]; }; then
    python3 -m venv "$wt/.venv"
    "$wt/.venv/bin/pip" install -q -e "$wt" pytest || \
      echo "warn: could not install deps for $wt; the repair task may not run" >&2
  fi
done

cat > "$ROOT/work/experiment.env" <<ENV
# Generated by harness/setup_test.sh — source before running the suite.
export BASELINE_TOOLS='$BASE_TOOLS'
export ENHANCED_TOOLS='$TOOL_TOOLS'
export CODEINTEL_EXT='$CODEINTEL_EXT'
export PI_PROVIDER='${MODEL%%/*}'
export PI_MODEL='${MODEL##*/}'
export PI_THINKING='$THINKING'
ENV

cat > "$ROOT/work/EXPERIMENT.json" <<JSON
{
  "repo": "$REPO",
  "tool": "${TOOL:-}",
  "codeintel_extension": "$CODEINTEL_EXT",
  "enhanced_tools": "$TOOL_TOOLS",
  "baseline_tools": "$BASE_TOOLS",
  "model": "$MODEL",
  "thinking": "$THINKING"
}
JSON

echo "prepared work/experiment-baseline and work/experiment-enhanced"
echo "environment written to work/experiment.env"
if [ -z "$CODEINTEL_EXT" ] && [ -n "$TOOL" ]; then
  echo "warn: could not detect an extension entry under '$TOOL'; set CODEINTEL_EXT manually" >&2
fi
echo
echo "next:"
echo "  source work/experiment.env"
echo "  harness/run_suite.sh run1"
echo "  harness/evaluate.py run1"
